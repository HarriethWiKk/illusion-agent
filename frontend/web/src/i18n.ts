/**
 * 获取国际化文本
 *
 * 根据当前语言和文本键获取对应的翻译文本。
 * 如果指定语言中不存在该键，则回退到中文文本。
 * 如果中文中也不存在，则返回键名本身。
 *
 * @param lang - 当前 UI 语言
 * @param key - 文本标识符
 * @returns 对应语言的翻译文本
 */
export function t(lang: UiLanguage, key: string): string {
  if (lang === 'en') return EN[key] || ZH[key] || key;
  return ZH[key] || key;
}
